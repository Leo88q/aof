type Copy = { messages: Record<ApiErrorCode, string>; unknownCode: (code: string) => string; unexpected: (status: number) => string; networkUnavailable: string };
const messages = (values: readonly string[]): Record<ApiErrorCode, string> => {
  if (values.length !== apiErrorCodes.length) throw new Error('Incomplete API error translations');
  return Object.fromEntries(apiErrorCodes.map((code, index) => [code, values[index]])) as Record<ApiErrorCode, string>;
};

