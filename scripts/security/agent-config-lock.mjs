#!/usr/bin/env node
/**
 * agent-config-lock — pin every file that instructs an AI agent or wires a
 * tool into one (MCP servers, editor agent configs, CLAUDE.md-style
 * instruction files, the audit prompt).
 *
 *   node scripts/security/agent-config-lock.mjs --check    # CI / readiness test
 *   node scripts/security/agent-config-lock.mjs --update   # after a reviewed change
 *
 * Why (SECURITY_CHECKLIST #78/#79 — tool poisoning, #74 — memory poisoning):
 * an agent trusts its instruction files and tool descriptions more than the
 * code. A one-line change to CLAUDE.md, a new MCP server in opencode.json or a
 * reworded tool description is exactly how an attacker (or a careless PR)
 * redirects what every future agent session does. Hashing these files into a
 * committed lock makes any such change a loud, separate diff
 * (`security/agent-config.lock.json`) that the readiness workflow refuses to
 * accept silently, and it catches NEW agent config files that nobody added on
 * purpose.
 *
 * The lock also records the SHA-256 of every MCP server entry / tool
 * description found in the known config formats, so a description rewrite is
 * visible even when the surrounding file is large.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { resolve, dirname, relative, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
const LOCK = resolve(ROOT, "security/agent-config.lock.json");
const mode = process.argv.includes("--update") ? "update" : "check";

/** Files and directories that steer agents. Missing entries are fine; unknown new ones are not. */
const CANDIDATE_FILES = [
  "CLAUDE.md", "QWEN.md", "AGENTS.md", "GEMINI.md", ".cursorrules", ".clinerules", ".windsurfrules",
  ".github/copilot-instructions.md", "PROMPT_AUDIT_FULL_STACK_V2.md", "docs/AI_AGENT_SECURITY_POLICY.md",
  "opencode.json", ".mcp.json", ".cursor/mcp.json", ".vscode/mcp.json", ".claude/settings.json", ".claude/mcp.json",
  ".gemini/settings.json", ".codex/config.toml", ".roo/mcp.json", ".continue/config.json", ".continue/config.yaml",
];
// [#130] Каталоги навыков — такой же исполняемый агентом текст, как MCP-описания:
// вредоносный навык может быть просто набором инструкций (инциденты ClawHub/OpenClaw 2026).
const CANDIDATE_DIRS = [".claude/commands", ".claude/agents", ".claude/skills", "skills", ".cursor/rules", ".github/instructions", ".github/prompts", ".roo", ".windsurf/rules", "prompts"];

const files = new Set(CANDIDATE_FILES.filter((f) => existsSync(resolve(ROOT, f))));
for (const d of CANDIDATE_DIRS) walk(resolve(ROOT, d), (f) => files.add(relative(ROOT, f)));

const entries = {};
for (const rel of [...files].sort()) {
  const buf = readFileSync(resolve(ROOT, rel));
  const entry = { sha256: sha(buf), bytes: buf.length };
  const tools = extractToolDescriptors(rel, buf.toString("utf8"));
  if (tools.length) entry.tools = tools;
  entries[rel] = entry;
}

if (mode === "update") {
  mkdirSync(dirname(LOCK), { recursive: true });
  writeFileSync(LOCK, JSON.stringify({ $comment: "Generated by scripts/security/agent-config-lock.mjs --update. Any diff here must be reviewed as a change to what AI agents are told to do.", updatedAt: new Date().toISOString(), files: entries }, null, 2) + "\n");
  console.log(`agent-config-lock: pinned ${Object.keys(entries).length} file(s) → ${relative(ROOT, LOCK)}`);
  process.exit(0);
}

if (!existsSync(LOCK)) {
  console.error("agent-config-lock: security/agent-config.lock.json is missing — run with --update and commit it");
  process.exit(1);
}
const lock = JSON.parse(readFileSync(LOCK, "utf8"));
const problems = [];
for (const [rel, e] of Object.entries(entries)) {
  const pinned = lock.files[rel];
  if (!pinned) problems.push(`NEW agent config file not in lock: ${rel}`);
  else if (pinned.sha256 !== e.sha256) {
    problems.push(`CHANGED: ${rel} (lock ${pinned.sha256.slice(0, 12)}… → now ${e.sha256.slice(0, 12)}…)`);
    const before = new Map((pinned.tools || []).map((t) => [t.id, t.sha256]));
    for (const t of e.tools || []) {
      if (!before.has(t.id)) problems.push(`  + new tool/server: ${t.id}`);
      else if (before.get(t.id) !== t.sha256) problems.push(`  ~ tool/server description changed: ${t.id}`);
    }
  }
}
for (const rel of Object.keys(lock.files)) if (!entries[rel]) problems.push(`REMOVED (was pinned): ${rel}`);

if (problems.length) {
  console.error("agent-config-lock: agent instruction/tool configuration drifted from security/agent-config.lock.json:");
  for (const p of problems) console.error("  " + p);
  console.error("If the change is intended and reviewed: node scripts/security/agent-config-lock.mjs --update, then commit the lock in the same change.");
  process.exit(1);
}
console.log(`agent-config-lock: ${Object.keys(entries).length} agent config file(s) match the lock`);

// ------------------------------------------------------------ helpers -----
function sha(buf) {
  return createHash("sha256").update(buf).digest("hex");
}
function walk(dir, fn) {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, fn);
    else if (st.isFile()) fn(p);
  }
}
/** Pull MCP server / tool descriptors out of the known config shapes. */
function extractToolDescriptors(rel, text) {
  if (!/\.(json)$/i.test(rel)) return [];
  let cfg;
  try {
    cfg = JSON.parse(text);
  } catch {
    return [];
  }
  const out = [];
  const servers = cfg.mcpServers || cfg.mcp || cfg.servers || {};
  for (const [name, def] of Object.entries(servers)) out.push({ id: `mcp:${name}`, sha256: sha(JSON.stringify(def)) });
  if (cfg.provider && typeof cfg.provider === "object") {
    for (const [name, def] of Object.entries(cfg.provider)) out.push({ id: `provider:${name}`, sha256: sha(JSON.stringify(def)) });
  }
  if (Array.isArray(cfg.tools)) for (const t of cfg.tools) out.push({ id: `tool:${t.name || t.id || sha(JSON.stringify(t)).slice(0, 8)}`, sha256: sha(JSON.stringify(t)) });
  return out;
}
